"""Writes docs/results/2026-09-24-track-a.md from data/track_a/summary_<grid>.json (no runs).

  uv run python docs/results/track_a_table.py
"""
import json
from pathlib import Path

ROUTERS = (("sensitivity", "3"), ("flip", "5"), ("regret", "6"), ("checklist", "checklist"), ("random", "random"),
           ("oracle", "oracle"))
OTHERS = (("sensitivity", "6−3"), ("flip", "6−5"), ("random", "6−random"), ("checklist", "6−checklist"))


def bp(x: float) -> str:
    return f"{x * 1e4:+.1f}".replace("-", "−")


def diff(d: dict) -> str:
    flag = " **W**" if d["router6_wins"] else " **L**" if d["mean"] > 0 and d["ci95"][0] > 0 else ""
    return f"{bp(d['mean'])} [{bp(d['ci95'][0])}, {bp(d['ci95'][1])}]{flag}"


def table(cells: list[dict]) -> list[str]:
    head = ["truth", "clue", "investigator", "priors", "budget", "slice", "n", *(n for _, n in ROUTERS),
            *(n for _, n in OTHERS)]
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for c in cells:
        if c["n"] == 0:
            continue  # fair-game truth has no decoy or interaction roles
        means = [f"{c['mean_regret'][r] * 1e4:.1f}" for r, _ in ROUTERS]
        diffs = [diff(c[f"regret_minus_{r}"]) for r, _ in OTHERS]
        out.append("| " + " | ".join([c["truth"], f"{c['clue']:.1f}", c["investigator"], c["level"],
                                      f"{c['share']:.0%}", c["slice"], str(c["n"]), *means, *diffs]) + " |")
    return out


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    lines = ["# Track A per-cell results (Plan 3, 2026-09-24)", "",
             "Generated by `uv run python docs/results/track_a_table.py` from `data/track_a/summary_<grid>.json`; "
             "do not edit by hand.", "",
             "Units: basis points of asking price (mean normalised regret × 10,000; lower is better). "
             "Routers: 3 sensitivity, 5 flip, 6 regret per page. Differences are router 6 minus the other router, "
             "mean over deals with a paired bootstrap 95% CI (2,000 resamples). "
             "**W**: router 6 wins (lower mean and the CI excludes zero, the pre-registered H2 rule). "
             "**L**: router 6 is significantly worse (the CI is above zero). "
             "Slices: all deals, decision-flip deals (`go != face_go`), deals with a decoy, deals with an "
             "interaction. The fair game (`self`) has no decoy or interaction roles.", ""]
    for grid, what in (("headline", "2,000 deals, perfect investigator, medium priors, both truths"),
                       ("full", "first 500 deals by filename, generator truth; its perfect/medium cells reuse the "
                                "headline rows for those 500 deals"),
                       ("hints", "first 500 deals by filename, generator truth, perfect investigator, medium priors; "
                                 "hints use the answer key (a \"what if\" study)")):
        s = json.loads((root / "data/track_a" / f"summary_{grid}.json").read_text())
        lines += [f"## {grid} ({what})", "", *table(s["cells"]), "",
                  f"Prior calibration: {', '.join(f'{k} {v:.2f}' for k, v in s['prior_calibration'].items())}. "
                  f"Sweep finds a forgotten problem in {s['sweep_find_rate']:.1%} of non-oracle runs.", ""]
    (root / "docs/results/2026-09-24-track-a.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
